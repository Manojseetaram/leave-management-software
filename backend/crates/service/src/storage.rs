use async_trait::async_trait;
use sha2::{Digest, Sha256};
use std::path::{Path, PathBuf};
use uuid::Uuid;

/// Private object-store boundary. Production deployments can replace the
/// local implementation with S3/object storage without changing the workflow.
#[async_trait]
pub trait PrivateStorage: Send + Sync {
    async fn put(&self, key: &str, bytes: &[u8]) -> Result<(), String>;
    async fn get(&self, key: &str) -> Result<Vec<u8>, String>;
    async fn delete(&self, key: &str) -> Result<(), String>;
}

#[derive(Debug, Clone)]
pub struct LocalPrivateStorage {
    root: PathBuf,
}

impl LocalPrivateStorage {
    pub fn new(root: PathBuf) -> Self {
        Self { root }
    }

    fn path_for(&self, key: &str) -> Result<PathBuf, String> {
        if !safe_storage_key(key) {
            return Err("invalid storage key".into());
        }
        Ok(self.root.join(key))
    }
}

/// Keys are generated by the server, never supplied by a client. This check is
/// defence in depth against traversal if a key is ever accepted from elsewhere.
pub fn safe_storage_key(key: &str) -> bool {
    !key.is_empty()
        && key.len() <= 200
        && key.split('/').all(|part| {
            !part.is_empty()
                && part != "."
                && part != ".."
                && part
                    .chars()
                    .all(|c| c.is_ascii_alphanumeric() || matches!(c, '-' | '_' | '.'))
        })
}

#[async_trait]
impl PrivateStorage for LocalPrivateStorage {
    async fn put(&self, key: &str, bytes: &[u8]) -> Result<(), String> {
        let path = self.path_for(key)?;
        let parent = path
            .parent()
            .ok_or_else(|| "invalid storage path".to_string())?;
        tokio::fs::create_dir_all(parent)
            .await
            .map_err(|e| format!("create storage directory: {e}"))?;

        // Write to a sibling temporary file and rename, so a failed write never
        // leaves a partial document that later looks valid.
        let tmp = parent.join(format!(".{}.tmp", Uuid::new_v4()));
        tokio::fs::write(&tmp, bytes)
            .await
            .map_err(|e| format!("write upload: {e}"))?;
        if let Err(e) = tokio::fs::rename(&tmp, &path).await {
            let _ = tokio::fs::remove_file(&tmp).await;
            return Err(format!("finalize upload: {e}"));
        }
        Ok(())
    }

    async fn get(&self, key: &str) -> Result<Vec<u8>, String> {
        let path = self.path_for(key)?;
        tokio::fs::read(path)
            .await
            .map_err(|e| format!("read upload: {e}"))
    }

    async fn delete(&self, key: &str) -> Result<(), String> {
        let path = self.path_for(key)?;
        match tokio::fs::remove_file(path).await {
            Ok(()) => Ok(()),
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(()),
            Err(e) => Err(format!("delete upload: {e}")),
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ScanVerdict {
    Clean,
    Infected(String),
}

/// Pluggable malware scanner. The mock is deliberately explicit; production
/// must supply a real scanning adapter and should fail closed if it is down.
#[async_trait]
pub trait MalwareScanner: Send + Sync {
    async fn scan(&self, bytes: &[u8], content_type: &str) -> Result<ScanVerdict, String>;
}

pub struct MockMalwareScanner;

#[async_trait]
impl MalwareScanner for MockMalwareScanner {
    async fn scan(&self, bytes: &[u8], _content_type: &str) -> Result<ScanVerdict, String> {
        // A tiny deterministic development heuristic: the EICAR marker is
        // rejected, everything else is treated as clean by the mock.
        if bytes.windows(5).any(|w| w == b"EICAR") {
            return Ok(ScanVerdict::Infected("EICAR test marker".into()));
        }
        Ok(ScanVerdict::Clean)
    }
}

/// Detects the allowed formats from their magic bytes, not the filename or the
/// client-supplied Content-Type.
pub fn detect_content_type(bytes: &[u8]) -> Option<(&'static str, &'static str)> {
    if bytes.starts_with(b"%PDF-") {
        return Some(("application/pdf", "pdf"));
    }
    if bytes.starts_with(&[0x89, b'P', b'N', b'G', 0x0d, 0x0a, 0x1a, 0x0a]) {
        return Some(("image/png", "png"));
    }
    if bytes.starts_with(&[0xff, 0xd8, 0xff]) {
        return Some(("image/jpeg", "jpg"));
    }
    if bytes.len() >= 12 && &bytes[0..4] == b"RIFF" && &bytes[8..12] == b"WEBP" {
        return Some(("image/webp", "webp"));
    }
    None
}

pub fn checksum_sha256(bytes: &[u8]) -> String {
    hex::encode(Sha256::digest(bytes))
}

pub fn storage_key(extension: &str) -> String {
    format!(
        "{}/{}.{}",
        chrono::Utc::now().format("%Y/%m"),
        Uuid::new_v4(),
        extension
    )
}

/// Keeps only the final path component and removes control characters. This is
/// metadata only; it is never used to construct a filesystem path.
pub fn sanitize_original_filename(raw: &str) -> String {
    let basename = Path::new(raw)
        .file_name()
        .and_then(|s| s.to_str())
        .unwrap_or("document");
    let cleaned: String = basename
        .chars()
        .filter(|c| !c.is_control())
        .take(255)
        .collect();
    if cleaned.trim().is_empty() {
        "document".into()
    } else {
        cleaned
    }
}

pub fn validate_document_type(raw: &str) -> Result<String, String> {
    let value = raw.trim().to_ascii_lowercase();
    if (1..=50).contains(&value.len())
        && value
            .chars()
            .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_')
    {
        Ok(value)
    } else {
        Err("document_type may contain only lower-case letters, digits and underscores".into())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn magic_bytes_are_authoritative() {
        assert_eq!(
            detect_content_type(b"%PDF-1.7").unwrap().0,
            "application/pdf"
        );
        assert_eq!(
            detect_content_type(&[0x89, b'P', b'N', b'G', 0x0d, 0x0a, 0x1a, 0x0a])
                .unwrap()
                .0,
            "image/png"
        );
        assert_eq!(
            detect_content_type(&[0xff, 0xd8, 0xff, 0xe0]).unwrap().0,
            "image/jpeg"
        );
        assert!(detect_content_type(b"<script>alert(1)</script>").is_none());
    }

    #[test]
    fn traversal_is_rejected_and_filenames_are_reduced() {
        for key in ["../secret", "a/../../b", "/etc/passwd", "a\\b", ""] {
            assert!(!safe_storage_key(key), "{key}");
        }
        assert!(safe_storage_key("2026/07/abc.pdf"));
        assert_eq!(sanitize_original_filename("../../etc/passwd"), "passwd");
        assert_eq!(
            sanitize_original_filename("bad\u{0}name.pdf"),
            "badname.pdf"
        );
    }

    #[test]
    fn checksum_is_hex_sha256() {
        let sum = checksum_sha256(b"hello");
        assert_eq!(sum.len(), 64);
        assert_eq!(
            sum,
            "2cf24dba5fb0a30e26e83b2ac5b9e29e1b161e5c1fa7425e73043362938b9824"
        );
    }

    #[tokio::test]
    async fn eicar_style_mock_is_reported() {
        let scanner = MockMalwareScanner;
        assert_eq!(
            scanner
                .scan(b"X5O!P%@AP[4\\PZX54(P^)7CC)7}$EICAR", "text/plain")
                .await
                .unwrap(),
            ScanVerdict::Infected("EICAR test marker".into())
        );
        assert_eq!(
            scanner.scan(b"%PDF-1.7", "application/pdf").await.unwrap(),
            ScanVerdict::Clean
        );
    }
}
